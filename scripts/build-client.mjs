import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import * as esbuild from "esbuild"
import postcss from "postcss"
import tailwind from "@tailwindcss/postcss"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const from = join(root, "plugin/harness.css")
const allowedRequires = new Set([
  "react",
  "react/jsx-runtime",
  "react-dom",
  "react-dom/client",
])

const compiled = await postcss([tailwind()]).process(readFileSync(from, "utf8"), { from })
let css = compiled.css.replaceAll(":root", ":host")
css = css.replace(/url\((['"]?)([^'")]+?\.woff2)\1\)/g, (match, _quote, spec) => {
  if (spec.startsWith("data:")) return match
  const file = resolve(dirname(from), spec)
  const data = readFileSync(file).toString("base64")
  return `url("data:font/woff2;base64,${data}")`
})
if (css.includes(":root")) throw new Error("Harness CSS still targets :root, so tokens would miss the shadow tree")
if (!css.includes("@font-face")) throw new Error("Harness CSS is missing the Outfit font")
if (!css.includes("@container studio")) throw new Error("Harness CSS is missing the studio container query")

const built = await esbuild.build({
  absWorkingDir: root,
  entryPoints: [join(root, "plugin/harness-entry.tsx")],
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: ["es2022"],
  jsx: "automatic",
  jsxDev: false,
  external: [...allowedRequires],
  define: {
    "process.env.NODE_ENV": '"production"',
    LANPOSE_STUDIO_CSS: JSON.stringify(css),
  },
  plugins: [
    {
      name: "at-alias",
      setup(build) {
        build.onResolve({ filter: /^@\// }, (args) => {
          const base = join(root, args.path.slice(2))
          const candidate = [".tsx", ".ts", ".js", ".mjs"].map((ext) => `${base}${ext}`).find((file) => existsSync(file))
          return { path: candidate ?? base }
        })
      },
    },
  ],
  write: false,
  minify: false,
  charset: "utf8",
  legalComments: "none",
})

const bundled = built.outputFiles[0].text
const requires = [...bundled.matchAll(/require\((["'])([^"']+)\1\)/g)].map((match) => match[2])
const unexpected = [...new Set(requires)].filter((id) => !allowedRequires.has(id))
if (unexpected.length > 0) {
  throw new Error(`Harness client requires modules the host does not share: ${unexpected.join(", ")}`)
}
if (bundled.includes("完整画廊在独立工作室里")) {
  throw new Error("Harness client still contains the simplified studio copy")
}

const client = `/* Generated by scripts/build-client.mjs from plugin/harness-entry.tsx. Do not edit by hand. */
window.__ModuleLoader__.load({ id: "gen-ai-pose-image", factory: (require) => {
  var module = { exports: {} };
  var exports = module.exports;
${bundled}
  module.exports.name = "gen-ai-pose-image";
  return module.exports;
}});
`
writeFileSync(join(root, "plugin/client.js"), client)
console.log(`wrote plugin/client.js (${client.length} bytes, css ${css.length} bytes)`)
