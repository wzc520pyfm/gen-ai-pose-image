function hairOf(tags) {
  const value = String(tags).toLowerCase()
  if (/very long|long hair|hime cut/.test(value)) return "长发"
  if (/medium hair/.test(value)) return "中发"
  if (/pixie|short hair|bob cut/.test(value)) return "短发"
  return "通用"
}

