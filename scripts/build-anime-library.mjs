function groups(items, key, labelKey) {
  const map = new Map()
  for (const item of items) {
    const id = item[key]
    const row = map.get(id) || { id, label: item[labelKey] || id, count: 0, adult: true }
    row.count += 1
    if (!item.adult) row.adult = false
    map.set(id, row)
  }
  return [...map.values()]
}

